/*
 * LDO voltage groups from Google's s2mpg12-register.h, in uV.
 * Group 2 is 300 mV / 12.5 mV, group 3 is 725 mV / 12.5 mV,
 * group 4 is 700 mV / 25 mV (LDO25M), group 5 is 1.8 V / 25 mV (LDO26M).
 */
#define S2MPG12_LDO_MIN_G2		300000
#define S2MPG12_LDO_STEP_G2		12500
#define S2MPG12_LDO_MIN_G3		725000
#define S2MPG12_LDO_STEP_G3		12500
#define S2MPG12_LDO_MIN_G4		700000
#define S2MPG12_LDO_STEP_G4		25000
#define S2MPG12_LDO_MIN_G5		1800000
#define S2MPG12_LDO_STEP_G5		25000

#define S2MPG12_LDO_ENABLE_TIME		128	/* us */

#endif /* __LINUX_MFD_S2MPG12_H */
